export function buildSentencePatternExplanations(book){
 const seen=new Set();
 return lessons.map(n=>{
  const jp=book.lines[n.sentence-1]?.t.map(i=>book.words[i].s).join(''),start=jp?.indexOf(n.quote),key=n.sentence+':'+n.quote;
  if(start==null||start<0||jp.indexOf(n.quote,start+1)!==-1||seen.has(key)||!n.parts.length||!n.pattern.examples.length||!n.pattern.structure.length||!n.why||!n.context||!n.recall)throw new Error('Invalid sentence pattern lesson: '+key);
  seen.add(key);return {...n,jp,start,end:start+n.quote.length};
 });
}
