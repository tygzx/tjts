export function buildSentencePatternExplanations(book){
 const seen=new Set();
 return lessons.map(n=>{
  const jp=book.lines[n.sentence-1]?.t.map(i=>book.words[i].s).join(''),start=jp?.indexOf(n.quote),key=n.sentence+':'+n.quote;
  if(start==null||start<0||jp.indexOf(n.quote,start+1)!==-1||seen.has(key)||!n.parts.length||!n.pattern.examples.length||!n.pattern.structure.length||!n.why||!n.context||!n.recall)throw new Error('Invalid sentence pattern lesson: '+key);
  const end=start+n.quote.length;
  let cursor=start;
  const parts=n.parts.map(p=>{
   if(!p.kana)return p;
   const from=jp.indexOf(p.ja,cursor),to=from+p.ja.length;
   if(from<cursor||to>end||!/^[\p{P}\s]*$/u.test(jp.slice(cursor,from)))throw new Error('Invalid word breakdown: '+key+' '+p.ja);
   cursor=to;
   return {...p,start:from,end:to};
  });
  if(parts.some(p=>p.kana)&&!/^[\p{P}\s]*$/u.test(jp.slice(cursor,end)))throw new Error('Incomplete word breakdown: '+key);
  seen.add(key);
  return {...n,parts,jp,start,end};
 });
}
