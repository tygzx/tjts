export function buildPlainExplanations(book){
 const keys=new Set();
 return notes.map(n=>{
  const jp=book.lines[n.sentence-1]?.t.map(i=>book.words[i].s).join(''),start=jp?.indexOf(n.quote);
  const key=n.sentence+':'+n.quote;
  if(start==null||start<0||jp.indexOf(n.quote,start+1)!==-1||keys.has(key)||!n.parts.length||!n.meaning||!n.link)throw new Error('Invalid plain explanation: '+key);
  keys.add(key);return {...n,jp,start,end:start+n.quote.length};
 });
}

